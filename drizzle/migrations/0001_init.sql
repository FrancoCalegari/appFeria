-- Esquema SQL estándar para Feria de las Heras (compatible con SQLite, PostgreSQL, MySQL y servicios SQL Cloud)

CREATE TABLE IF NOT EXISTS fair_settings (
  id INTEGER PRIMARY KEY,
  name VARCHAR(255) NOT NULL DEFAULT 'Feria de las Heras',
  cols INTEGER NOT NULL DEFAULT 7,
  rows INTEGER NOT NULL DEFAULT 21,
  updated_at VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'VENDOR',
  created_at VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS stalls (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL DEFAULT 'Verdulería',
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT,
  mp_aliases TEXT NOT NULL DEFAULT '[]',
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  x INTEGER,
  y INTEGER,
  w INTEGER NOT NULL DEFAULT 1,
  h INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS map_cells (
  x INTEGER NOT NULL,
  y INTEGER NOT NULL,
  type VARCHAR(32) NOT NULL DEFAULT 'PATH',
  PRIMARY KEY (x, y)
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  stall_id INTEGER NOT NULL REFERENCES stalls(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  price REAL NOT NULL,
  unit VARCHAR(32) NOT NULL DEFAULT 'kg',
  in_stock INTEGER NOT NULL DEFAULT 1,
  image_url TEXT
);

